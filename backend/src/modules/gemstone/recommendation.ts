/**
 * Deterministic Parashari Lagna-lord gemstone rules.
 *
 *  1. The Ascendant (Lagna) sign is found from the birth chart.
 *  2. Its ruler (the Lagna lord) gives the PRIMARY traditional gemstone.
 *  3. Optional SECONDARY perspectives: the rulers of the 5th and 9th houses
 *     (whole-sign), unless that ruler also owns the 6th, 8th or 12th house,
 *     and never repeating the primary planet.
 *  4. The lunar nodes own no sign, so Hessonite / Cat's Eye are never chosen
 *     by this method.
 *
 * Other schools (Moon-sign, Sun-sign, dasha-based, strength-based methods)
 * can reach different conclusions. Nothing here is generated by an LLM.
 */
import {
  DEBILITATION_SIGN,
  EXALTATION_SIGN,
  SIGNS,
  SIGN_LORD,
  STONE_FOR_PLANET,
  type GemstoneInfo,
  type Planet,
  type Sign,
} from "./gemstone.catalogue.js";
import { wholeSignHouse, type BirthChart } from "./chart.engine.js";

export interface ChartFactor {
  label: string;
  value: string;
}

export interface SecondaryPerspective {
  house: 5 | 9;
  planet: Planet;
  stone: GemstoneInfo;
  sign: Sign;
  reason: string;
}

export interface Recommendation {
  lagnaSign: Sign;
  lagnaLord: Planet;
  lagnaLordSign: Sign;
  lagnaLordHouse: number;
  primary: GemstoneInfo;
  secondary: SecondaryPerspective[];
  excluded: { house: 5 | 9; planet: Planet; reason: string }[];
  factors: ChartFactor[];
  cautions: string[];
}

/** Houses (1-12) owned by a planet when the given sign is the Ascendant. */
export const housesOwnedBy = (planet: Planet, lagnaSignIndex: number): number[] => {
  const houses: number[] = [];
  for (let i = 0; i < 12; i++) {
    if (SIGN_LORD[SIGNS[i]] === planet) {
      houses.push(wholeSignHouse(lagnaSignIndex, i));
    }
  }
  return houses.sort((a, b) => a - b);
};

const ordinal = (n: number) =>
  n === 1 ? "1st" : n === 2 ? "2nd" : n === 3 ? "3rd" : `${n}th`;

export const recommend = (chart: BirthChart): Recommendation => {
  const asc = chart.ascendant;
  const lagnaLord = SIGN_LORD[asc.sign];
  const lordPos = chart.planets[lagnaLord];
  const lordHouse = wholeSignHouse(asc.signIndex, lordPos.signIndex);
  const primary = STONE_FOR_PLANET[lagnaLord];

  const factors: ChartFactor[] = [
    { label: "Ascendant (Lagna)", value: `${asc.sign} ${asc.degreeInSign.toFixed(1)}°` },
    { label: "Lagna lord", value: lagnaLord },
    {
      label: `${lagnaLord} placement`,
      value: `${lordPos.sign} (${ordinal(lordHouse)} house)`,
    },
  ];

  const cautions: string[] = [];
  if (DEBILITATION_SIGN[lagnaLord] === lordPos.sign) {
    cautions.push(
      `The Lagna lord ${lagnaLord} is in ${lordPos.sign}, a sign traditionally called its debilitation. Many practitioners advise consulting a qualified astrologer before relying on its stone.`,
    );
  }
  if (EXALTATION_SIGN[lagnaLord] === lordPos.sign) {
    factors.push({ label: "Dignity", value: `${lagnaLord} is in its sign of exaltation` });
  }
  if ([6, 8, 12].includes(lordHouse)) {
    cautions.push(
      `The Lagna lord sits in the ${ordinal(lordHouse)} house, which some traditions regard as a difficult placement. Interpretations differ between schools.`,
    );
  }
  if (lagnaLord === "Saturn") {
    cautions.push(
      "Blue Sapphire is traditionally treated with particular caution; many practitioners suggest a trial period under qualified guidance.",
    );
  }

  const secondary: SecondaryPerspective[] = [];
  const excluded: Recommendation["excluded"] = [];
  for (const house of [5, 9] as const) {
    const sign = SIGNS[(asc.signIndex + house - 1) % 12];
    const planet = SIGN_LORD[sign];
    const owned = housesOwnedBy(planet, asc.signIndex);
    const dusthana = owned.filter((h) => h === 6 || h === 8 || h === 12);
    if (planet === lagnaLord) {
      excluded.push({
        house,
        planet,
        reason: `${planet} rules the ${ordinal(house)} house and is already the Lagna lord.`,
      });
    } else if (dusthana.length > 0) {
      excluded.push({
        house,
        planet,
        reason: `${planet} rules the ${ordinal(house)} house but also owns the ${dusthana.map(ordinal).join(" and ")} house, so it is excluded.`,
      });
    } else if (!secondary.some((s) => s.planet === planet)) {
      secondary.push({
        house,
        planet,
        stone: STONE_FOR_PLANET[planet],
        sign,
        reason: `${planet} rules the ${ordinal(house)} house (${sign}) and owns no 6th, 8th or 12th house.`,
      });
    }
  }

  return {
    lagnaSign: asc.sign,
    lagnaLord,
    lagnaLordSign: lordPos.sign,
    lagnaLordHouse: lordHouse,
    primary,
    secondary,
    excluded,
    factors,
    cautions,
  };
};
